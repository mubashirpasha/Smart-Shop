package com.example.data.local.preferences

import android.content.Context
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.booleanPreferencesKey
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.intPreferencesKey
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.datastore.preferences.preferencesDataStore
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

val Context.dataStore: DataStore<Preferences> by preferencesDataStore(name = "karobarflow_prefs")

enum class ThemeMode {
    SYSTEM, DARK, LIGHT
}

data class AppSettings(
    val storeName: String = "Smart Shop Store",
    val country: String = "Pakistan",
    val currencyName: String = "Pakistani Rupee",
    val currencyCode: String = "PKR",
    val currencySymbol: String = "Rs.",
    val dateFormat: String = "DD-MM-YYYY",
    val phoneCountryCode: String = "+92",
    val timezone: String = "Asia/Karachi",
    val lowStockThreshold: Int = 5,
    val themeMode: ThemeMode = ThemeMode.LIGHT,
    val language: String = "en", // "en" for English, "ur" for Urdu
    val businessCategory: String = "General Store",
    val businessPhone: String = "",
    val businessAddress: String = "",
    val businessNtn: String = "",
    val invoiceTemplate: String = "STANDARD", // STANDARD, THERMAL, DETAILED
    val invoiceFooter: String = "Thank you for your business! Computerized tax invoice generated by Smart Shop.",
    val invoiceShowTaxNumber: Boolean = true,
    val invoiceShowCustomerPhone: Boolean = true,
    val invoiceShowShopAddress: Boolean = true,
    val isOnboardingCompleted: Boolean = true,
    val soundEffectsEnabled: Boolean = true
)

class ShopFlowPreferences(private val context: Context) {

    private object Keys {
        val STORE_NAME = stringPreferencesKey("store_name")
        val COUNTRY = stringPreferencesKey("country")
        val CURRENCY_NAME = stringPreferencesKey("currency_name")
        val CURRENCY_CODE = stringPreferencesKey("currency_code")
        val CURRENCY_SYMBOL = stringPreferencesKey("currency_symbol")
        val DATE_FORMAT = stringPreferencesKey("date_format")
        val PHONE_COUNTRY_CODE = stringPreferencesKey("phone_country_code")
        val TIMEZONE = stringPreferencesKey("timezone")
        val LOW_STOCK_THRESHOLD = intPreferencesKey("low_stock_threshold")
        val THEME_MODE = stringPreferencesKey("theme_mode")
        val LANGUAGE = stringPreferencesKey("app_language")
        val BUSINESS_CATEGORY = stringPreferencesKey("business_category")
        val BUSINESS_PHONE = stringPreferencesKey("business_phone")
        val BUSINESS_ADDRESS = stringPreferencesKey("business_address")
        val BUSINESS_NTN = stringPreferencesKey("business_ntn")
        val INVOICE_TEMPLATE = stringPreferencesKey("invoice_template")
        val INVOICE_FOOTER = stringPreferencesKey("invoice_footer")
        val INVOICE_SHOW_TAX = booleanPreferencesKey("invoice_show_tax")
        val INVOICE_SHOW_PHONE = booleanPreferencesKey("invoice_show_phone")
        val INVOICE_SHOW_ADDRESS = booleanPreferencesKey("invoice_show_address")
        val ONBOARDING_COMPLETED = booleanPreferencesKey("onboarding_completed")
        val SOUND_EFFECTS = booleanPreferencesKey("sound_effects")
    }

    val appSettingsFlow: Flow<AppSettings> = context.dataStore.data.map { preferences ->
        val storeName = preferences[Keys.STORE_NAME] ?: "Smart Shop Store"
        val country = preferences[Keys.COUNTRY] ?: "Pakistan"
        val currencyName = preferences[Keys.CURRENCY_NAME] ?: "Pakistani Rupee"
        val currencyCode = preferences[Keys.CURRENCY_CODE] ?: "PKR"
        val currency = preferences[Keys.CURRENCY_SYMBOL] ?: "Rs."
        val dateFormat = preferences[Keys.DATE_FORMAT] ?: "DD-MM-YYYY"
        val phoneCode = preferences[Keys.PHONE_COUNTRY_CODE] ?: "+92"
        val timezone = preferences[Keys.TIMEZONE] ?: "Asia/Karachi"
        val lowStock = preferences[Keys.LOW_STOCK_THRESHOLD] ?: 5
        val themeModeStr = preferences[Keys.THEME_MODE] ?: ThemeMode.LIGHT.name
        val themeMode = runCatching { ThemeMode.valueOf(themeModeStr) }.getOrDefault(ThemeMode.LIGHT)
        val language = preferences[Keys.LANGUAGE] ?: "en"
        val category = preferences[Keys.BUSINESS_CATEGORY] ?: "General Store"
        val phone = preferences[Keys.BUSINESS_PHONE] ?: ""
        val address = preferences[Keys.BUSINESS_ADDRESS] ?: ""
        val ntn = preferences[Keys.BUSINESS_NTN] ?: ""
        val template = preferences[Keys.INVOICE_TEMPLATE] ?: "STANDARD"
        val footer = preferences[Keys.INVOICE_FOOTER] ?: "Thank you for your business! Computerized tax invoice generated by Smart Shop."
        val showTax = preferences[Keys.INVOICE_SHOW_TAX] ?: true
        val showPhone = preferences[Keys.INVOICE_SHOW_PHONE] ?: true
        val showAddress = preferences[Keys.INVOICE_SHOW_ADDRESS] ?: true
        val onboardingCompleted = preferences[Keys.ONBOARDING_COMPLETED] ?: true
        val soundEffects = preferences[Keys.SOUND_EFFECTS] ?: true

        AppSettings(
            storeName = storeName,
            country = country,
            currencyName = currencyName,
            currencyCode = currencyCode,
            currencySymbol = currency,
            dateFormat = dateFormat,
            phoneCountryCode = phoneCode,
            timezone = timezone,
            lowStockThreshold = lowStock,
            themeMode = themeMode,
            language = language,
            businessCategory = category,
            businessPhone = phone,
            businessAddress = address,
            businessNtn = ntn,
            invoiceTemplate = template,
            invoiceFooter = footer,
            invoiceShowTaxNumber = showTax,
            invoiceShowCustomerPhone = showPhone,
            invoiceShowShopAddress = showAddress,
            isOnboardingCompleted = onboardingCompleted,
            soundEffectsEnabled = soundEffects
        )
    }

    suspend fun updateStoreName(name: String) {
        context.dataStore.edit { preferences ->
            preferences[Keys.STORE_NAME] = name
        }
    }

    suspend fun updateCurrencySymbol(symbol: String, code: String = "PKR", name: String = "Pakistani Rupee") {
        context.dataStore.edit { preferences ->
            preferences[Keys.CURRENCY_SYMBOL] = symbol
            preferences[Keys.CURRENCY_CODE] = code
            preferences[Keys.CURRENCY_NAME] = name
        }
    }

    suspend fun updateThemeMode(mode: ThemeMode) {
        context.dataStore.edit { preferences ->
            preferences[Keys.THEME_MODE] = mode.name
        }
    }

    suspend fun updateLanguage(lang: String) {
        context.dataStore.edit { preferences ->
            preferences[Keys.LANGUAGE] = lang
        }
    }

    suspend fun updateBusinessCategory(category: String) {
        context.dataStore.edit { preferences ->
            preferences[Keys.BUSINESS_CATEGORY] = category
        }
    }

    suspend fun updateBusinessProfile(phone: String, address: String, ntn: String) {
        context.dataStore.edit { preferences ->
            preferences[Keys.BUSINESS_PHONE] = phone
            preferences[Keys.BUSINESS_ADDRESS] = address
            preferences[Keys.BUSINESS_NTN] = ntn
        }
    }

    suspend fun updateFullBusinessProfile(
        storeName: String,
        category: String,
        phone: String,
        address: String,
        ntn: String
    ) {
        context.dataStore.edit { preferences ->
            if (storeName.isNotBlank()) {
                preferences[Keys.STORE_NAME] = storeName
            }
            preferences[Keys.BUSINESS_CATEGORY] = category
            preferences[Keys.BUSINESS_PHONE] = phone
            preferences[Keys.BUSINESS_ADDRESS] = address
            preferences[Keys.BUSINESS_NTN] = ntn
        }
    }

    suspend fun updateInvoiceSettings(
        template: String,
        footer: String,
        showTax: Boolean,
        showPhone: Boolean,
        showAddress: Boolean
    ) {
        context.dataStore.edit { preferences ->
            preferences[Keys.INVOICE_TEMPLATE] = template
            preferences[Keys.INVOICE_FOOTER] = footer
            preferences[Keys.INVOICE_SHOW_TAX] = showTax
            preferences[Keys.INVOICE_SHOW_PHONE] = showPhone
            preferences[Keys.INVOICE_SHOW_ADDRESS] = showAddress
        }
    }

    suspend fun updateInvoiceFooter(footer: String) {
        context.dataStore.edit { preferences ->
            preferences[Keys.INVOICE_FOOTER] = footer
        }
    }


    suspend fun updateOnboardingCompleted(completed: Boolean) {
        context.dataStore.edit { preferences ->
            preferences[Keys.ONBOARDING_COMPLETED] = completed
        }
    }

    suspend fun updateLowStockThreshold(threshold: Int) {
        context.dataStore.edit { preferences ->
            preferences[Keys.LOW_STOCK_THRESHOLD] = threshold
        }
    }
}
